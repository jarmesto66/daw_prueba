let suma; /* Declaración de la variable suma */
let num1 = parseInt(prompt("Introduce el primer número:")); /* Pedimos el primer número */
let num2 = parseInt(prompt("Introduce el segundo número:")); /* Pedimos el segundo número */
suma = num1 + num2; /* Sumamos los dos números y almacenamos el resultado en la variable suma */
alert("La suma de " + num1 + " y " + num2 + " es: " + suma); /* Mostramos el resultado de la suma en una alerta */